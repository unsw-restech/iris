#!/bin/bash
# bin/issue-tick against a fake `gh` on PATH. Prints each failed case and
# nothing on success, so bin/check can run it.
#
#   tests/bin/test_issue_tick.sh
#
# bin/check name: issue-tick test

cd "$(dirname "$(readlink -f "$0")")/../.." || exit 1
fake="$(mktemp -d)"
trap 'rm -rf "$fake"' EXIT

# `gh issue view --json body` prints $fake/body, and `--json comments`
# prints $fake/brief as the latest Agent Brief comment, id 42, if it exists.
# `gh issue edit` saves stdin to $fake/edited and `gh api -X PATCH` on
# comment 42 to $fake/brief-edited, so a case that must not edit leaves no
# such file.
cat > "$fake/gh" <<'FAKE'
#!/bin/bash
dir="$(dirname "$0")"
case "$*" in
    "issue view "*"--json body "*) cat "$dir/body" ;;
    "issue view "*"--json comments "*) if [ -e "$dir/brief" ]; then echo 42; cat "$dir/brief"; fi ;;
    "issue edit "*) cat > "$dir/edited" ;;
    "api -X PATCH repos/{owner}/{repo}/issues/comments/42 -F body=@-") cat > "$dir/brief-edited" ;;
    *) echo "fake gh: unexpected call: $*" >&2; exit 1 ;;
esac
FAKE
chmod +x "$fake/gh"

body='## Acceptance criteria

- [ ] The sample dataset arrives in `/srv/scratch/<zID>/` intact
- [ ] **Open in Globus** appears under **Files**
  - [ ] Nested box with a back\slash
- [x] Already ticked box, written as "- [ ] " in text
```
- [ ] Fenced box
```
- [ ] Twin box one
- [ ] Twin box two'

# expect <exit code> <output substring> <arg>...
expect() {
    local want="$1" grep_for="$2" out rc
    shift 2
    printf '%s\n' "$body" > "$fake/body"
    rm -f "$fake/edited" "$fake/brief-edited"
    out="$(PATH="$fake:$PATH" bin/issue-tick "$@" 2>&1)"
    rc=$?
    if [ "$rc" != "$want" ]; then
        echo "issue-tick $*: exit $rc, expected $want"
        echo "$out" | sed 's/^/  /'
    elif ! grep -qF -- "$grep_for" <<< "$out"; then
        echo "issue-tick $*: output lacks '$grep_for'"
        echo "$out" | sed 's/^/  /'
    fi
}

expect 0 "ticked on #95: **Open in Globus**" 95 'The sample dataset' '**Open in Globus**' 'Nested box with a back\slash'
want="${body//- \[ \] The/- [x] The}"
want="${want//- \[ \] \*\*Open/- [x] **Open}"
want="${want//- \[ \] Nested/- [x] Nested}"
[ "$(cat "$fake/edited" 2>/dev/null)" = "$want" ] || { echo "issue-tick: edited body differs:"; diff <(echo "$want") "$fake/edited" | sed 's/^/  /'; }

expect 0 "every box already ticked" 95 'Already ticked'
[ -e "$fake/edited" ] && echo "issue-tick: edited a body with nothing to tick"
expect 1 "matches 2 boxes" 95 'The sample dataset' 'Twin box'
[ -e "$fake/edited" ] && echo "issue-tick: edited a body although a prefix matched two boxes"
expect 1 "matches 0 boxes" 95 'No such box'
expect 1 "matches 0 boxes" 95 'Fenced box'
expect 1 "matches 0 boxes" 95 'sample dataset'
expect 2 "usage:" 95

# The Agent Brief comment: tried only when the body doesn't settle every
# prefix, and edited, never the body, when it does.
brief='> *This was generated by AI during triage.*

## Agent Brief

**Acceptance criteria:**
- [ ] The new ADR exists
- [ ] `bin/check` passes'
printf '%s\n' "$brief" > "$fake/brief"
expect 0 "ticked on #146's Agent Brief: The new ADR" 146 'The new ADR' '`bin/check`'
[ -e "$fake/edited" ] && echo "issue-tick: edited the body for boxes in the brief"
want="${brief//- \[ \]/- [x]}"
[ "$(cat "$fake/brief-edited" 2>/dev/null)" = "$want" ] || { echo "issue-tick: edited brief differs:"; diff <(echo "$want") "$fake/brief-edited" | sed 's/^/  /'; }
expect 0 "ticked on #95: **Open in Globus**" 95 '**Open in Globus**'
[ -e "$fake/brief-edited" ] && echo "issue-tick: edited the brief for a box in the body"
expect 1 "matches 0 boxes" 146 'The new ADR' '**Open in Globus**'
[ -e "$fake/edited" ] || [ -e "$fake/brief-edited" ] && echo "issue-tick: edited although no one place had every box"
rm "$fake/brief"
